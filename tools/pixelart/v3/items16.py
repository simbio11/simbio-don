def _all():
    out = {}
    for k, rows in ITEMS.items():
        out[f"px16_item_{k}"] = rows
    for k, rows in SHOP.items():
        out[f"px16_{k}"] = rows
    return out


def outputs():
    """{그림 이름: 16×16 RGBA 그림}. 이름은 drawable-nodpi 파일 이름 그대로."""
    out = {}
    for name, rows in _all().items():
        assert len(rows) == SIZE, f"{name}: 줄 수 {len(rows)} != {SIZE}"
        check(name, rows, SIZE, PALETTE)
        out[name] = img(rows, PALETTE)
    return out
